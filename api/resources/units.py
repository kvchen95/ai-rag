"""单位、中文数字与量的正则表（详细设计.md §10.1 第三道 / §10.2）。

运行时代码不直接写中文单位与中文数字，统一从这里取，保证校验口径只有一份。
"""

from __future__ import annotations

import re
from decimal import Decimal

# 单位归一表：写法 → (规范单位, 折算系数)。
#
# 折算只做"量纲内换算"（万元→元、亿→元、成→%），**不做跨量纲的等价**
# （工作日≠天、月≠30 天）。§10.2 的反例点名了这条。
UNIT_TABLE: dict[str, tuple[str, Decimal]] = {
    "万元": ("元", Decimal(10000)),
    "亿元": ("元", Decimal(100000000)),
    "千元": ("元", Decimal(1000)),
    "元": ("元", Decimal(1)),
    "块": ("元", Decimal(1)),
    "个工作日": ("工作日", Decimal(1)),
    "工作日": ("工作日", Decimal(1)),
    "天": ("天", Decimal(1)),
    "日": ("天", Decimal(1)),
    "个月": ("月", Decimal(1)),
    "月": ("月", Decimal(1)),
    "年": ("年", Decimal(1)),
    "小时": ("小时", Decimal(1)),
    "分钟": ("分钟", Decimal(1)),
    "星期": ("周", Decimal(1)),
    "周": ("周", Decimal(1)),
    "次": ("次", Decimal(1)),
    "人": ("人", Decimal(1)),
    "份": ("份", Decimal(1)),
    "条": ("条", Decimal(1)),
    "页": ("页", Decimal(1)),
    "项": ("项", Decimal(1)),
    "倍": ("倍", Decimal(1)),
    "个百分点": ("百分点", Decimal(1)),
    "%": ("%", Decimal(1)),
    "％": ("%", Decimal(1)),
    "成": ("%", Decimal(10)),
}

# 长的先匹配：「个工作日」必须在「日」之前，否则会切出一个「个」+「工作日」
# 的怪组合。
_UNITS = "|".join(
    sorted((re.escape(unit) for unit in UNIT_TABLE), key=len, reverse=True)
)

CN_DIGITS: dict[str, int] = {
    "零": 0,
    "〇": 0,
    "一": 1,
    "两": 2,
    "二": 2,
    "三": 3,
    "四": 4,
    "五": 5,
    "六": 6,
    "七": 7,
    "八": 8,
    "九": 9,
}
CN_UNITS: dict[str, int] = {"十": 10, "百": 100, "千": 1000}
CN_BIG: dict[str, int] = {"万": 10000, "亿": 100000000}

# 日期：先摘掉，避免拆成三个裸数字。
DATE_PATTERNS = (
    re.compile(
        r"(?P<y>\d{4})\s*[-/年]\s*(?P<m>\d{1,2})\s*[-/月]\s*(?P<d>\d{1,2})\s*[日号]?"
    ),
    re.compile(r"(?P<y>\d{4})\s*年\s*(?P<m>\d{1,2})\s*月"),
    re.compile(r"(?P<y>\d{4})-(?P<m>\d{1,2})(?![\d-])"),
)

# 阿拉伯数字 + 可选单位。千分位逗号与全角数字都在这里归一。
ARABIC = re.compile(
    r"(?P<num>\d[\d,，]*(?:\.\d+)?)\s*(?P<unit>" + _UNITS + r")?"
)
# 范围分隔符：`500-600 元` / `500 至 600 元`。第二个数的单位要回填给第一个。
RANGE_TAIL = re.compile(
    r"\s*(?:-|~|～|—|–|至|到)\s*\d[\d,，]*(?:\.\d+)?\s*(?P<unit>"
    + _UNITS
    + r")"
)
# 中文数字 + 必带单位（不带单位的中文数字一律不认）。
#
# 前置守卫 `(?<![第这那每某几哪上前后])`：`第一步` `这一条` `那两天` 里的字是
# **序数/指代**，不是量。不挡它们，`这一条` 会被抽成 `1 条`，然后第三道校验拿着
# 一个从来不存在的"1 条"去证据里找，每条答案都判不过——而错的地方在这里。
CHINESE = re.compile(
    r"(?<![第这那每某几哪上前后])(?P<cn>[零〇一两二三四五六七八九十百千万亿]+)\s*(?P<unit>"
    + _UNITS
    + r")"
)
# 百分之X / 千分之X
CHINESE_PERCENT = re.compile(
    r"(?P<kind>百分之|千分之)\s*(?P<cn>[零〇一两二三四五六七八九十百千万亿]+|\d[\d.]*)"
)

# 专名只校验格式固定的条款号与编码。机构名、公司名、部门名没有可靠的中文
# 分词边界，不能用“后缀 + 向前回退”的启发式去猜；这一类由 judge 语义校验。
PROPER_EXACT = (
    re.compile(r"第[零〇一两二三四五六七八九十百\d]{1,4}[条章节款项]"),
    re.compile(r"[A-Z]{2,}[/-]?[A-Z]?\s?\d{2,}(?:-\d+)?",),
)

# 属性名：数字前面紧邻的那个中文短语（"住宿费限额为 **500** 元"）。
ATTR = re.compile(
    r"([\u4e00-\u9fa5]{2,12})\s*(?:为|是|按|不超过|最多|最少|不低于|达|约|：|:)?\s*$"
)
# 属性名尾部可能是连接词（"住宿费限额为" 里的「为」被贪婪的字符类吃进去了），
# 剥掉才好与另一个句子里的「住宿费限额」对上。
ATTR_TRAILING = ("为", "是", "按", "达", "约", "的", "了", "和", "与", "及")
ATTR_STRIP_PREFIX = (
    "每人每天",
    "每人每月",
    "每人每年",
    "每人",
    "每天",
    "每月",
    "每年",
    "每日",
    "单个",
    "其中",
    "合计",
    "共计",
    "总计",
)

# 千分比：五 / 千分之五 的换算口径。
PER_MILLE = "千分之"
# 引用定位「第 66 页」的前缀。
ORDINAL_PREFIX = "第"
# 年份单位：属于查询/报告期范围，不参与数值校验。
YEAR_UNIT = "年"
# 冲突审计里缺单位时的展示。
NO_UNIT_LABEL = "（无单位）"
